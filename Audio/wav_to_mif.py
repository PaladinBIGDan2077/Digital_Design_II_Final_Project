"""
wav_to_mif.py
-------------
Converts a mono 16-bit 8 kHz WAV file to a Quartus MIF (Memory Initialization
File) for use with the IP Catalog ROM generator (altsyncram megafunction).

MIF is the native Quartus format for ROM initialization

Usage:
    python wav_to_mif.py sound.wav sound.mif

Requirements:
    WAV must be MONO, 16-BIT SIGNED PCM, 8000 Hz.

"""
import sys
import wave
import struct

ROM_DEPTH  = 66000
DATA_WIDTH = 16

def wav_to_mif(wav_filename, mif_filename, rom_depth=ROM_DEPTH):
    with wave.open(wav_filename, 'rb') as f:
        channels  = f.getnchannels()
        sampwidth = f.getsampwidth()
        framerate = f.getframerate()
        raw       = f.readframes(f.getnframes())
    if sampwidth != 2:
        raise ValueError(f"WAV must be 16-bit. Got {sampwidth * 8}-bit.\n")
    if channels != 1:
        raise ValueError(f"WAV must be mono. Got {channels} channels.\n")
    if framerate != 8000:
        raise ValueError(f"WAV must be 8000 Hz. Got {framerate} Hz.\n")
    samples = list(struct.unpack(f'<{len(raw) // 2}h', raw))
    n_audio = len(samples)
    print(f"Read {n_audio} samples ({n_audio / 8000:.2f} s) from {wav_filename}")
    if n_audio > rom_depth:
        print(f"WARNING: audio longer than ROM depth, truncating "
              f"{n_audio - rom_depth} samples")
        samples  = samples[:rom_depth]
        n_audio  = rom_depth
    n_padding = rom_depth - n_audio
    if n_padding > 0:
        print(f"Padding with {n_padding} silent samples "f"(written as a single MIF range entry)")
    # Write MIF file
    addr_width = max(1, (rom_depth - 1).bit_length())
    with open(mif_filename, 'w') as out:
        # Header
        out.write(f'-- Quartus MIF generated by wav_to_mif.py\n')
        out.write(f'-- Source: {wav_filename}\n')
        out.write(f'-- Audio:  {n_audio} samples ({n_audio / 8000:.2f} s) 'f'+ {n_padding} samples silence padding\n')
        out.write(f'\n')
        out.write(f'DEPTH = {rom_depth};\n')
        out.write(f'WIDTH = {DATA_WIDTH};\n')
        out.write(f'\n')
        out.write(f'ADDRESS_RADIX = HEX;\n')
        out.write(f'DATA_RADIX    = HEX;\n')
        out.write(f'\n')
        out.write(f'CONTENT BEGIN\n')
        # Audio samples, one address per line
        for addr, sample in enumerate(samples):
            # Store as unsigned 16-bit two's complement (same bit pattern)
            word = sample & 0xFFFF
            out.write(f'    {addr:{addr_width}X} : {word:04X};\n')
        if n_padding > 0:
            start = n_audio
            end   = rom_depth - 1
            out.write(f'    [{start:{addr_width}X}..{end:{addr_width}X}] : 0000;\n')
        out.write(f'END;\n')
    print(f"Wrote {mif_filename}")

if __name__ == '__main__':
    if len(sys.argv) != 3:
        print("Usage: python wav_to_mif.py input.wav output.mif")
        sys.exit(1)

    wav_to_mif(sys.argv[1], sys.argv[2])
